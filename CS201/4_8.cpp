#include<iostream>
using namespace std;

int main(){
    int number = 5;
    switch(number){
        case 1:
        cout << "\n\n number is 1";
        break;
        
        case 2:
        cout << "\n\n number is 2";
        break;

        case 3:
        cout << "\n\n number is 3";
        break;

        case 4:
        cout << "\n\n number is 4";
        break;

        case 5:
        cout << "\n\n number is 5";
        break;

        default:
        cout << "invalid input"; 
    }
}